-- POR QUE NULL Y NO NOT NULL (decision consciente)
--   La columna arranca vacia a proposito. YA existen filas en planes_viaje, asi
--   que un NOT NULL sin DEFAULT haria fallar el ALTER sobre ellas; y un NOT
