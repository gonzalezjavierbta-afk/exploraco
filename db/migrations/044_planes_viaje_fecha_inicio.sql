-- CARACTER DE LA MIGRACION
--   ADITIVA: SOLO ALTER TABLE planes_viaje ADD COLUMN y un CREATE INDEX. Nada
--   de DROP, nada de ALTER COLUMN, nada de RENAME, nada de SET NOT NULL, nada
